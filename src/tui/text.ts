// Width-aware string helpers for the full-screen view. Everything here understands ANSI escapes and
// wide characters, so a nerd-font glyph, an emoji and a CJK title all land in the right cell.
import { stripVTControlCharacters } from 'node:util';
import stringWidth from 'string-width';

// This only splits the SGR styles emitted by Chalk; it is not an input sanitizer.
const ANSI = /(\x1b\[[0-9;:]*m)/;
const segmenter = new Intl.Segmenter(undefined, { granularity: 'grapheme' });

/** Convert external content to plain, single-line text BEFORE applying UI styles.
 * Node strips recognized VT sequences. Removing remaining control characters also makes
 * incomplete or unknown sequences inert; their printable fragments may remain visible.
 */
export function plainText(s: string): string {
  return stripVTControlCharacters(s).replace(/\s/gu, ' ').replace(/\p{Cc}/gu, '');
}

/** Pasted text made safe to edit: escapes and control characters gone. One line (newlines become
 * spaces) unless `multiline`, which keeps line breaks and turns tabs into `tab` spaces. A single
 * trailing newline, which copying a whole line usually brings along, is dropped. */
export function pasteText(text: string, multiline = false, tab = 4): string {
  const t = text.replace(/\r\n?/g, '\n').replace(/\n$/, '');
  if (!multiline) return plainText(t);
  return t.split('\n').map((line) => plainText(line.replace(/\t/g, ' '.repeat(tab)))).join('\n');
}

// The ASCII icon set's frame is ASCII through and through: what pages and the kit write in their text
// (arrows, dots, dashes, ellipses, quotes, box lines) is spelled with one ASCII character each, so every
// row keeps its width. Anything else (a goal in Japanese) is left as it is.
const ASCII: Record<string, string> = {
  '…': '.', '·': '-', '•': '*', '—': '-', '–': '-', '‐': '-', '−': '-',
  '↑': '^', '↓': 'v', '←': '<', '→': '>', '↔': '-', '⇢': '>', '‹': '<', '›': '>', '«': '<', '»': '>', '≤': '<', '≥': '>',
  '“': '"', '”': '"', '„': '"', '‘': "'", '’': "'", '×': 'x', '✓': 'v', '✗': 'x', '❯': '>', '●': 'o', '○': 'o', '▌': '|',
  '─': '-', '━': '-', '╌': '-', '│': '|', '┃': '|', '╭': '+', '╮': '+', '╰': '+', '╯': '+',
  '┌': '+', '┐': '+', '└': '+', '┘': '+', '├': '+', '┤': '+', '┬': '+', '┴': '+', '┼': '+',
};
const ASCII_CHARS = new RegExp(`[${Object.keys(ASCII).join('')}]`, 'gu');

/** `s` with the typographic characters the app uses replaced by ASCII ones of the same width; styles are kept. */
export function asciiText(s: string): string {
  return s.replace(ASCII_CHARS, (ch) => ASCII[ch]!);
}

// Layout helpers accept plain text or trusted styles generated by our theme, never raw output.

// Most of what is drawn is ASCII, Latin letters, punctuation, arrows and box lines: characters that
// are one cell each and never join into wider graphemes (no combining marks, no emoji, no CJK). For a
// string made only of them, its width is its length once the styles are taken out, which spares the
// full grapheme measurement on every row of every frame. Anything else is measured by string-width.
// The ranges are checked against string-width, character by character, in the kit tests.
export const NARROW = /^[\x20-\x7e\xa0-\xac\xae-\u02ff\u2010-\u2027\u2030-\u205e\u2190-\u22ff\u2500-\u259f\u25a0-\u25fc\u25ff\u270c-\u2727\u2758-\u2794]*$/;
const STYLES = /\x1b\[[0-9;:]*m/g;

/** Cells `s` takes on screen (styles count for nothing). */
export function measure(s: string): number {
  const bare = s.includes('\x1b') ? s.replace(STYLES, '') : s;
  return NARROW.test(bare) ? bare.length : stringWidth(s);
}

export const width = (s: string): number => measure(s);

/**
 * Where the graphemes of `cps` (a string split into code points) start, as code point offsets, ending
 * with `cps.length`. An emoji with its variation selector, a keycap or a letter with its accent is one
 * grapheme: cursors stop and rows break only at these offsets.
 */
export function graphemeStops(cps: readonly string[]): number[] {
  const stops = [0];
  let at = 0;
  for (const { segment } of segmenter.segment(cps.join(''))) {
    at += [...segment].length;
    stops.push(at);
  }
  if (stops.at(-1) !== cps.length) stops.push(cps.length);
  return stops;
}

/** The grapheme boundary before code point offset `i` (0 at the start). */
export function prevStop(cps: readonly string[], i: number): number {
  const stops = graphemeStops(cps);
  let best = 0;
  for (const s of stops) { if (s < i) best = s; else break; }
  return best;
}

/** The grapheme boundary after code point offset `i` (`cps.length` at the end). */
export function nextStop(cps: readonly string[], i: number): number {
  for (const s of graphemeStops(cps)) if (s > i) return s;
  return cps.length;
}

/** Cut to `w` cells, keeping escapes intact and ending with an ellipsis when something was dropped. */
export function fit(s: string, w: number, ellipsis = '…'): string {
  if (w <= 0) return '';
  if (measure(s) <= w) return s;
  const budget = w - measure(ellipsis);
  let out = '';
  let used = 0;
  for (const part of s.split(ANSI)) {
    if (part.startsWith('\x1b')) { out += part; continue; }
    for (const { segment } of segmenter.segment(part)) {
      const cw = measure(segment);
      if (used + cw > budget) return out + '\x1b[0m' + ellipsis;
      out += segment;
      used += cw;
    }
  }
  return out + ellipsis;
}

/** A log message as one line of at most `w` cells: its first line, with an ellipsis when more followed. */
export function logLine(msg: string, w: number): string {
  const [first = '', ...rest] = msg.split('\n');
  const cut = fit(rest.some((l) => l.trim()) ? `${first} …` : first, w);
  return cut.includes('\x1b[') && !cut.endsWith('\x1b[0m') ? cut + '\x1b[0m' : cut;
}

/** Exactly `w` cells: cut or right-padded. A line that fits is measured once. */
export function cell(s: string, w: number): string {
  if (w <= 0) return '';
  const sw = measure(s);
  if (sw <= w) return s + ' '.repeat(w - sw);
  const cut = fit(s, w);
  return cut + ' '.repeat(Math.max(0, w - measure(cut)));
}

/** Plain `text` in at most `w` cells, cut in the middle with an ellipsis, so both ends stay (a path keeps its file name). */
export function midFit(text: string, w: number): string {
  if (measure(text) <= w) return text;
  if (w <= 1) return fit(text, w);
  const parts = Array.from(segmenter.segment(text), (x) => x.segment);
  const room = w - 1;
  let head = '';
  for (const p of parts) { if (measure(head + p) > Math.ceil(room * 0.4)) break; head += p; }
  let tail = '';
  for (let i = parts.length - 1; i >= 0 && measure(parts[i]! + tail) <= room - measure(head); i--) tail = parts[i]! + tail;
  return `${head}…${tail}`;
}

/** Left part and right part on one line of `w` cells, the right part kept whole when it fits. */
export function spread(left: string, right: string, w: number): string {
  const rw = measure(right);
  if (rw >= w) return cell(right, w);
  return cell(left, w - rw) + right;
}

/** Word-wrap plain text to `w` cells; at most `maxLines` lines, the last one truncated. */
export function wrap(text: string, w: number, maxLines = Infinity): string[] {
  const lines: string[] = [];
  for (const para of plainText(text).replace(/\s+/gu, ' ').trim().split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      if (!word) continue;
      const candidate = line ? `${line} ${word}` : word;
      if (measure(candidate) <= w) { line = candidate; continue; }
      if (line) lines.push(line);
      line = measure(word) <= w ? word : fit(word, w);
    }
    if (line) lines.push(line);
  }
  if (lines.length > maxLines) {
    const kept = lines.slice(0, maxLines);
    kept[maxLines - 1] = fit(kept[maxLines - 1]! + ' ' + lines.slice(maxLines).join(' '), w);
    return kept;
  }
  return lines;
}

/**
 * Word-wrap plain text keeping its own line breaks: each line is wrapped on its own and blank lines
 * stay (a run of them becomes one; leading and trailing ones go). A word longer than a row is broken
 * across rows instead of cut, so a path or a URL can be read whole. At most `maxLines` lines, the last
 * one ending in an ellipsis when something was left out. `wrap()` is the one-paragraph form.
 */
export function wrapParagraphs(text: string, w: number, maxLines = Infinity): string[] {
  const cols = Math.max(1, w);
  const lines: string[] = [];
  for (const raw of text.replace(/\r\n?/g, '\n').split('\n')) {
    const para = plainText(raw).replace(/\s+/gu, ' ').trim();
    if (!para) { if (lines.length && lines.at(-1) !== '') lines.push(''); continue; }
    let line = '';
    for (const word of para.split(' ')) {
      const candidate = line ? `${line} ${word}` : word;
      if (measure(candidate) <= cols) { line = candidate; continue; }
      if (line) lines.push(line);
      if (measure(word) <= cols) { line = word; continue; }
      const parts = chop(word, cols);
      lines.push(...parts.slice(0, -1));
      line = parts.at(-1) ?? '';
    }
    if (line) lines.push(line);
  }
  while (lines.at(-1) === '') lines.pop();
  if (lines.length <= maxLines) return lines;
  if (maxLines < 1) return [];
  const kept = lines.slice(0, maxLines);
  while (kept.length > 1 && kept.at(-1) === '') kept.pop();
  const rest = lines.slice(kept.length).filter(Boolean).join(' ');
  // What is left joins the last line, cut with an ellipsis (or fits there, with nothing lost).
  kept[kept.length - 1] = fit(`${kept.at(-1)} ${rest}`.trim(), cols);
  return kept;
}

/** Plain text in lines of at most `w` cells with nothing dropped, for what must be read whole (a command to approve). */
export function chop(text: string, w: number): string[] {
  const lines: string[] = [];
  let line = '';
  let used = 0;
  for (const { segment } of segmenter.segment(plainText(text))) {
    const cw = measure(segment);
    if (used + cw > w && line) { lines.push(line); line = ''; used = 0; }
    line += segment;
    used += cw;
  }
  return [...lines, line];
}

export function repeat(ch: string, n: number): string {
  return n > 0 ? ch.repeat(n) : '';
}

/** A bar of `w` cells, `ratio` of it lit. */
export function bar(ratio: number, w: number, on: string, off: string, lit: (s: string) => string, dim: (s: string) => string): string {
  const n = Math.round(Math.max(0, Math.min(1, ratio)) * w);
  return lit(repeat(on, n)) + dim(repeat(off, w - n));
}
